// Copies the workflow deployment handoff into the frontend's public assets.
//
//   node scripts/sync-deployment.mjs [--handoff <deployment.json>] [--network <network.json>] [--abi-dir <docs/abi>]
//
// Writes:
//   public/imd-deployment.json   runtime deployment configuration (assets filled in after build)
//   public/abi/<Contract>.json   raw ABI arrays copied byte for byte from docs/abi
//   src/config/launch.ts         pool key parameters and deployment block taken from the handoff
//
// The ABI hash of every handoff contract is checked against canonicalKeccak(abi) before writing.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { canonicalKeccak, readJson } from './lib.mjs';

const here = path.dirname(fileURLToPath(import.meta.url));
const webRoot = path.resolve(here, '..');
const repoRoot = path.resolve(webRoot, '..');

const args = process.argv.slice(2);
const opt = (name, fallback) => {
  const i = args.indexOf(name);
  return i >= 0 && args[i + 1] ? args[i + 1] : fallback;
};
const handoffPath = opt('--handoff', path.join(repoRoot, '.imd/reads/deployment.json'));
const networkPath = opt('--network', path.join(repoRoot, '.imd/reads/network.json'));
const abiDir = opt('--abi-dir', path.join(repoRoot, 'docs/abi'));

// Contracts created inside Realm's constructor. They have no handoff entry; the app discovers
// their addresses on chain (Realm.diplomacy(), Realm.season(), Season.banners()).
const CHILD_CONTRACTS = ['Diplomacy', 'Season', 'Banners'];

const handoff = readJson(handoffPath);
const network = fs.existsSync(networkPath) ? readJson(networkPath) : null;

if (handoff.version !== 1) throw new Error(`unsupported handoff version ${handoff.version}`);
for (const key of ['launchId', 'chainId', 'sourceCommit', 'attestationHash']) {
  if (handoff[key] === undefined) throw new Error(`handoff missing ${key}`);
}

fs.mkdirSync(path.join(webRoot, 'public/abi'), { recursive: true });

const contracts = [];
for (const c of handoff.contracts) {
  const src = path.join(abiDir, `${c.name}.json`);
  const bytes = fs.readFileSync(src);
  const abi = JSON.parse(bytes.toString('utf8'));
  if (!Array.isArray(abi)) throw new Error(`${src} is not a raw ABI array`);
  const hash = canonicalKeccak(abi);
  if (hash !== c.abiHash) {
    throw new Error(`ABI hash mismatch for ${c.name}: handoff ${c.abiHash}, computed ${hash}`);
  }
  fs.writeFileSync(path.join(webRoot, 'public/abi', `${c.name}.json`), bytes);
  contracts.push({ name: c.name, address: c.address, abiHash: c.abiHash, abiPath: `abi/${c.name}.json` });
  console.log(`ok   ${c.name} ${c.address} abi ${hash.slice(0, 12)}…`);
}
for (const name of CHILD_CONTRACTS) {
  const src = path.join(abiDir, `${name}.json`);
  const bytes = fs.readFileSync(src);
  if (!Array.isArray(JSON.parse(bytes.toString('utf8')))) throw new Error(`${src} is not a raw ABI array`);
  fs.writeFileSync(path.join(webRoot, 'public/abi', `${name}.json`), bytes);
  console.log(`ok   ${name} (child contract, address read from chain)`);
}

const manifest = {
  version: 1,
  launchId: handoff.launchId,
  chainId: handoff.chainId,
  sourceCommit: handoff.sourceCommit,
  attestationHash: handoff.attestationHash,
  contracts,
  assets: [],
};
if (network) {
  manifest.network = network.network;
  if (network.walletAddChain) manifest.walletAddChain = network.walletAddChain;
}
fs.writeFileSync(path.join(webRoot, 'public/imd-deployment.json'), JSON.stringify(manifest, null, 2) + '\n');
console.log('ok   public/imd-deployment.json');

const pool = handoff.manifest?.pool;
{
  const zero = '0x0000000000000000000000000000000000000000';
  const hookEntry = handoff.contracts.find((c) => /hook/i.test(c.name));
  const startBlock = handoff.contracts.reduce((min, c) => (min === null || c.blockNumber < min ? c.blockNumber : min), null);
  const launchTs = `// Generated by scripts/sync-deployment.mjs from the deployment handoff. Do not edit by hand.
// Build-time facts that are not part of imd-deployment.json: the Uniswap v4 pool key parameters
// of the launch token's pool (currency1 is the token, whose address the app reads from the
// runtime manifest) and the block at which the contracts were deployed, used as the lower bound
// for event log scans. The app double-checks the block against chain code before using it.
export const POOL = {
  fee: ${Number(pool?.fee ?? 0)},
  tickSpacing: ${Number(pool?.tickSpacing ?? 0)},
  pairedCurrency: '${pool?.pairedCurrency ?? zero}',
  hooks: '${hookEntry ? hookEntry.address : zero}',
  initialPrice: '${pool?.initialPrice ?? ''}',
} as const;

export const START_BLOCK = ${startBlock ?? 0}n;
`;
  fs.mkdirSync(path.join(webRoot, 'src/config'), { recursive: true });
  fs.writeFileSync(path.join(webRoot, 'src/config/launch.ts'), launchTs);
  console.log('ok   src/config/launch.ts');
}
